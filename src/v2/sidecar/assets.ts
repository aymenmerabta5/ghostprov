export const V2_SIDECAR_REVISIONS = Object.freeze([V2_R1, V2_R2, V2_R3, V2_R4] as const);

export type V2SidecarRevision = (typeof V2_SIDECAR_REVISIONS)[number];

/**
 * Immutable sidecar releases and wire-protocol revisions deliberately have
 * separate version spaces. R3 and R4 contain newer sidecar implementations
 * while remaining byte-compatible with the R2 wire protocol.
 */
export function protocolRevisionForV2SidecarRevision(
  revision: V2SidecarRevision,
): ProtocolRevision {
  return revision === V2_R1 ? "r1" : "r2";
}

export interface V2SidecarReleaseIdentity {
  readonly revision: V2SidecarRevision;
  readonly protocolRevision: ProtocolRevision;
  readonly buildHash: string;
  readonly schemaHash: string;
  readonly bundleSha256: string;
}

