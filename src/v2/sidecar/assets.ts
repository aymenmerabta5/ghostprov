/**
 * Immutable sidecar releases and wire-protocol revisions deliberately have
 * separate version spaces. R3/R4 use standard R2 transport; R5-R8 keep R2
 * frame semantics while selecting a separately hashed bulk transport profile.
 */
export function protocolRevisionForV2SidecarRevision(
  revision: V2SidecarRevision,
): ProtocolRevision {
  return revision === V2_R1 ? "r1" : "r2";
}

export function transportProfileForV2SidecarRevision(
  revision: V2SidecarRevision,
): V2TransportProfile {
  return revision === V2_R5 || revision === V2_R6 || revision === V2_R7 || revision === V2_R8 || revision === V2_R9 || revision === V2_R10
    ? "bulk-v1"
    : DEFAULT_V2_TRANSPORT_PROFILE;
}

